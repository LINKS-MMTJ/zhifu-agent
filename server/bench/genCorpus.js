// 用法：node bench/genCorpus.js [--out ../knowledge]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Document, Packer, Paragraph, HeadingLevel, TextRun } from 'docx';

function fontPath() {
  const candidates = [
    'C:/Windows/Fonts/simhei.ttf',
    'C:/Windows/Fonts/simfang.ttf',
    '/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc',
    '/System/Library/Fonts/PingFang.ttc',
  ];
  return candidates.find((p) => fs.existsSync(p)) || null;
}

function pdfFrom(title, blocks) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margins: { top: 56, bottom: 56, left: 60, right: 60 }, info: { Title: title } });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const font = fontPath();
    if (font) doc.registerFont('cn', font);
    const useFont = () => { if (font) doc.font('cn'); };

    useFont();
    doc.fontSize(20).text(title, { align: 'left' });
    doc.moveDown(0.8);

    for (const b of blocks) {
      useFont();
      if (b.h) { doc.moveDown(0.4); doc.fontSize(13).text(b.h); doc.moveDown(0.3); }
      if (b.p) { doc.fontSize(10.5).text(b.p, { lineGap: 4 }); doc.moveDown(0.5); }
      if (b.li) { doc.fontSize(10.5).text(`· ${b.li}`, { indent: 12, lineGap: 3 }); }
    }
    doc.end();
  });
}


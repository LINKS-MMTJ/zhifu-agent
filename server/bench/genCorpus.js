function docxFrom(sections) {
  const children = [];
  for (const s of sections) {
    if (s.h1) children.push(new Paragraph({ text: s.h1, heading: HeadingLevel.HEADING_1 }));
    if (s.h2) children.push(new Paragraph({ text: s.h2, heading: HeadingLevel.HEADING_2 }));
    if (s.p) children.push(new Paragraph({ children: [new TextRun({ text: s.p })] }));
    if (s.bullet) children.push(new Paragraph({ text: s.bullet, bullet: { level: 0 } }));
  }
  return Packer.toBuffer(new Document({
    creator: '智服售后运营中心',
    title: sections[0]?.h1 || '售后规则',
    sections: [{ children }],
  }));
}

